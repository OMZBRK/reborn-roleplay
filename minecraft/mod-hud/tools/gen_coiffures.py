# ───────────────────────── ombrage ─────────────────────────
def _hash(s):
    return int(hashlib.md5(s.encode("utf-8")).hexdigest()[:8], 16)


def _brins(seed, n):
    """Variation par colonne (mèches) : valeurs dans [-0.06, 0.08], déterministes."""
    vals = (-0.06, -0.02, 0.0, 0.03, 0.06, 0.08)
    out, h = [], seed
    for _ in range(n):
        h = (h * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(vals[(h >> 16) % len(vals)])
    return out


MODS = {"#": 0.0, "+": 0.13, "-": -0.12, "x": -0.32}


def ombrer(grille, face, seconde, seed, ton, bande=None):
    """Grille ASCII -> tableau h×w de luminances (NaN = vide)."""
    h, w = len(grille), len(grille[0])
    v = np.full((h, w), np.nan, np.float32)
    br = _brins(seed + _hash(face), w)
    corps = face.startswith("c")
    for j, ligne in enumerate(grille):
        assert len(ligne) == w, f"{face}: ligne {j} de longueur {len(ligne)} (attendu {w})"
        for i, c in enumerate(ligne):
            if c == ".":
                continue
            if c == "o":
                v[j, i] = 1.0
                continue
            if face == "T":
                val = 0.80 + br[i] + (0.03 if j >= 6 else 0.0)
            elif face in ("D", "cT"):
                val = 0.50 + br[i] * 0.5
            else:                                    # faces verticales : mèches + dégradé
                val = 0.70 + br[i] - (0.012 if corps else 0.025) * j
                dessous = grille[j + 1][i] if j + 1 < h else "."
                if dessous == "." and not (face == "B" and j == h - 1 and not corps):
                    val -= 0.09                      # pointe
                g_ = ligne[i - 1] if i > 0 else "#"
                d_ = ligne[i + 1] if i + 1 < w else "#"
                if g_ == "." or d_ == ".":
                    val -= 0.04                      # bord de mèche
            if bande is not None and face in ("F", "R", "L", "B"):
                if j == bande and br[i] >= 0.0:
                    val += 0.13                      # bande de brillance (anime)
                elif j == bande + 1 and br[i] >= 0.03:
                    val += 0.06
            if seconde:
                val += 0.06
            v[j, i] = val + MODS.get(c, 0.0) + ton
    return v


def construire(st):
    """Style -> image 64x64 RGBA en niveaux de gris."""
    faces = dict(st)
    faces.setdefault("T", plein())
    if "R" in faces and "L" not in faces:
        faces["L"] = miroir(faces["R"])
    if "hR" in faces and "hL" not in faces:
        faces["hL"] = miroir(faces["hR"])
    for k in ("cR", "cL", "cF", "cB", "cT"):         # corps : base = seconde couche par défaut
        if "h" + k in faces and k not in faces:
            faces[k] = faces["h" + k]
    if "hcR" in faces and "hcL" not in faces:
        faces["hcL"] = miroir(faces["hcR"])
        faces.setdefault("cL", faces["hcL"])
    seed = _hash(st["id"])
    ton = st.get("ton", 0.0)
    lum = np.full((64, 64), np.nan, np.float32)
    for cle, g in faces.items():
        seconde = cle.startswith("h")
        face = cle[1:] if seconde else cle
        if face not in FACES:
            continue
        x, y, w, h = couche2(face) if seconde else FACES[face]
        assert len(g) == h, f"{st['id']} {cle}: {len(g)} lignes (attendu {h})"
        lum[y:y + h, x:x + w] = ombrer(g, face, seconde, seed, ton, st.get("bande"))
    # reflet : garantit luma max = blanc (teinte identique d'une coiffure à l'autre)
    for (i, j) in ((10, 5), (11, 6)):
        if not np.isnan(lum[j, i]):
            lum[j, i] = 1.0
    op = ~np.isnan(lum)
    g8 = np.clip(np.nan_to_num(lum) * 255.0 + 0.5, 0, 255).astype(np.uint8)
    rgba = np.zeros((64, 64, 4), np.uint8)
    for c in range(3):
        rgba[..., c] = np.where(op, g8, 0)
    rgba[..., 3] = np.where(op, 255, 0)
    return Image.fromarray(rgba, "RGBA")


