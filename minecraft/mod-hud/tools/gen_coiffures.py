def maj_catalogue(styles):
    with open(CATALOG, encoding="utf-8") as f:
        cat = json.load(f)
    hair = cat.setdefault("hair", [])
    connus = {a["id"] for a in hair}
    ajout = 0
    for st in styles:
        if st["id"] in connus:
            continue
        e = {"id": st["id"], "name": st["nom"], "tint": "all"}
        if st.get("genre"):
            e["gender"] = st["genre"]
        hair.append(e)
        ajout += 1
    with open(CATALOG, "w", encoding="utf-8", newline="\n") as f:
        json.dump(cat, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return ajout


# ───────────────────────── planche de contrôle ─────────────────────────
COULEURS = (("noir", "2A2630"), ("blond", "F0D080"), ("rose", "F09AC0"))


def planche(chemin, ids=None, echelle=5, colonnes=2):
    sys.path.insert(0, os.path.join(ICI, "style"))
    import perso                                     # noqa: E402
    from PIL import ImageDraw, ImageFont
    perso._CAT = None
    hair = perso.catalogue()["hair"]
    if ids:
        hair = [a for a in hair if a["id"] in ids]
    try:
        police = ImageFont.truetype("arial.ttf", 15)
        petite = ImageFont.truetype("arial.ttf", 12)
    except OSError:
        police = petite = ImageFont.load_default()
    vues = (("face", 0.0, 0.0), ("3/4", 34.0, 10.0), ("dos", 150.0, 10.0))
    cellules = []
    for a in hair:
        femme = a.get("gender") == "female"
        rendus = []
        for _, col in COULEURS:
            sk = perso.compose(sexe="femme" if femme else "homme", teint=3,
                               tenue="Complet_Femme1" if femme else "tenueh46",
                               cheveux=a["id"], couleur_cheveux=col, sourcils="2A2022")
            for _, lac, tan in vues:
                rendus.append(perso.rendu_buste(sk, echelle, lacet=lac, tangage=tan, bas=12))
        cellules.append((a, rendus))
    pw = max(r.width for _, rs in cellules for r in rs)
    ph = max(r.height for _, rs in cellules for r in rs)
    gap = 6
    cw = 9 * pw + 8 * gap + 2 * 14 + 24
    ch = ph + 34
    lignes = (len(cellules) + colonnes - 1) // colonnes
    entete = 40
    img = Image.new("RGBA", (cw * colonnes, entete + ch * lignes), (38, 30, 36, 255))
    d = ImageDraw.Draw(img)
    d.text((12, 10), "Coiffures Reborn — face / 3/4 / dos — noir, blond, rose "
                     f"({len(cellules)} coiffures)", fill=(240, 220, 170, 255), font=police)
    for k, (a, rs) in enumerate(cellules):
        x0 = (k % colonnes) * cw + 12
        y0 = entete + (k // colonnes) * ch
        d.rectangle([x0 - 6, y0, x0 + cw - 18, y0 + ch - 6], fill=(52, 42, 50, 255))
        g = {"female": "F", "male": "H"}.get(a.get("gender"), "H/F")
        d.text((x0, y0 + 4), f"{a['id']}  ·  {a['name']}  ·  {g}", fill=(240, 220, 170, 255), font=petite)
        x = x0
        for n, r in enumerate(rs):
            img.alpha_composite(r, (x + (pw - r.width) // 2, y0 + 24 + (ph - r.height)))
            x += pw + gap + (14 if n % 3 == 2 else 0)
    os.makedirs(os.path.dirname(os.path.abspath(chemin)), exist_ok=True)
    img.convert("RGB").save(chemin)
    return len(cellules)


