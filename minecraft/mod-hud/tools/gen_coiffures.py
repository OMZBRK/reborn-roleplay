def couche2(face):
    x, y, w, h = FACES[face]
    return (x + 32, y, w, h) if not face.startswith("c") else (x, y + 16, w, h)


def plein(w=8, h=8):
    return ["#" * w] * h


def miroir(g):
    return [r[::-1] for r in g]


