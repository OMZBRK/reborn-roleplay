def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--planche", help="chemin de la planche de contrôle PNG")
    ap.add_argument("--seul", nargs="*", help="ne générer / montrer que ces ids")
    ap.add_argument("--sans-catalogue", action="store_true", help="ne pas toucher à catalog.json")
    a = ap.parse_args()
    styles = [s for s in STYLES if not a.seul or s["id"] in a.seul]
    os.makedirs(HAIR, exist_ok=True)
    for st in styles:
        construire(st).save(os.path.join(HAIR, st["id"] + ".png"))
    print(f"{len(styles)} coiffures écrites dans {os.path.normpath(HAIR)}")
    if not a.sans_catalogue:
        print(f"catalog.json : {maj_catalogue(STYLES)} entrée(s) ajoutée(s)")
    if a.planche:
        n = planche(a.planche, a.seul)
        print(f"planche : {n} coiffures -> {a.planche}")


if __name__ == "__main__":
    main()
