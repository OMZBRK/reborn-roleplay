# -*- coding: utf-8 -*-
"""Coiffures du créateur de personnage (couche cheveux 64x64, prêtes à teinter).

Génère dans src/main/resources/assets/reborn/textures/character/hair/ un PNG par
coiffure décrite dans STYLES, et ajoute les entrées manquantes à catalog.json (les
entrées existantes ne sont jamais modifiées ni réordonnées).

Usage :
    python tools/gen_coiffures.py                    # PNG + catalog.json
    python tools/gen_coiffures.py --planche <png>    # + planche de contrôle (toutes les
                                                     #   coiffures, face / 3/4 / dos, 3 couleurs)
    python tools/gen_coiffures.py --seul Cheveux_Hime --planche x.png   # une ou plusieurs
(Pillow + numpy ; la planche réutilise tools/style/perso.py.)

Gabarit = les coiffures de l'équipe (Cheveux_Base, Cheveux_Itachi…) :
  * calque de base : dessus du crâne plein, côtés / arrière / frange sur la tête ;
  * seconde couche (chapeau, gonflée de 0,5 texel) : mèches et pointes qui donnent le
    volume ; corps (veste, +0,25) pour ce qui tombe dans le dos ou sur la poitrine ;
  * niveaux de gris : RebornSkins teinte en mode tint=all, couleur × (luma / luma max) ;
    chaque coiffure contient donc un reflet blanc (luma max = 255) pour que la même
    couleur choisie donne le même rendu d'une coiffure à l'autre.

Description d'une coiffure : une grille ASCII par face, vue DE L'EXTÉRIEUR (comme
l'UV Minecraft) :
    T  dessus   8x8  ligne 0 = arrière du crâne, ligne 7 = front ; col 0 = côté droit du perso
    D  dessous  8x8  ligne 0 = menton/avant, ligne 7 = nuque
    F  face     8x8  col 0 = côté droit du perso (gauche de l'écran)
    R  côté droit du perso   8x8  col 0 = arrière, col 7 = avant
    L  côté gauche du perso  8x8  col 0 = avant,   col 7 = arrière  (miroir de R par défaut)
    B  arrière  8x8  col 0 = côté gauche du perso (vue de dos : gauche de l'écran)
    cT cF cB 8 de large, cR cL 4 de large : le corps (épaules 4 lignes, faces 12 lignes)
Préfixe h = seconde couche (hT, hF…, hcB…). Une face corps donnée en seconde couche
seulement est recopiée en base (une tenue à veste masquerait sinon les cheveux du dos).
Caractères :  . vide   # cheveu   + clair   - sombre   x très sombre (lien, raie)
              o reflet (blanc)
L'ombrage est procédural : mèches verticales (variation par colonne), dégradé haut→bas,
pointes et bords assombris, seconde couche légèrement plus claire.
"""
